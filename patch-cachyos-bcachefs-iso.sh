#!/usr/bin/env bash
# Version 2.0: ORIGINAL ISO input; complete installer build included.
# Convert an ORIGINAL CachyOS desktop ISO into a bcachefs/tiering installer ISO.
# Usage: bash patch-cachyos-bcachefs-iso.sh INPUT.iso [OUTPUT.iso]
# Missing host dependencies are installed automatically with pacman (via sudo).
# Builds baseline x86-64 Calamares and both bcachefs DKMS modules inside the image.
# Requires network and roughly 50-70 GiB free. Original unsigned Archiso only.
# A new ISO is written; an existing destination is never overwritten.
set -Eeuo pipefail
export LC_ALL=C
fail() { printf '\nERROR: %s\n' "$*" >&2; exit 1; }
if [[ ${1:-} == --help || $# == 0 ]]; then
    sed -n '2,8p' "$0"
    exit 0
fi
[[ $# -le 2 ]] || fail 'Usage: bash patch-cachyos-bcachefs-iso.sh INPUT.iso [OUTPUT.iso]'
[[ -f $1 ]] || fail 'Input must be an existing ISO file, not a disk/device.'
[[ $(uname -m) == x86_64 ]] || fail "Build host must be x86_64."
for suffix in build-report.txt calamares.pkg.tar.zst; do
    [[ ! -e ${2:-${1%.*}-bcachefs-fixed.iso}.$suffix && ! -L ${2:-${1%.*}-bcachefs-fixed.iso}.$suffix ]] || fail "Output sidecar already exists: $suffix"
done
rootcmd=()
if (( EUID != 0 )); then
    command -v sudo >/dev/null || fail 'sudo is required; install it or run the script as root.'
    sudo -v
    rootcmd=(sudo)
fi
# Host tools only; compilers and kernel build dependencies go inside the image.
dependencies=()
command -v xorriso >/dev/null || dependencies+=(xorriso)
if ! command -v unsquashfs >/dev/null || ! command -v mksquashfs >/dev/null; then
    dependencies+=(squashfs-tools)
fi
command -v python3 >/dev/null || dependencies+=(python)
command -v cmp >/dev/null || dependencies+=(diffutils)
command -v arch-chroot >/dev/null || dependencies+=(arch-install-scripts)
command -v unshare >/dev/null || dependencies+=(util-linux)
command -v tar >/dev/null || dependencies+=(tar)
command -v gzip >/dev/null || dependencies+=(gzip)
command -v pacman >/dev/null || fail 'Run on CachyOS/Arch with CachyOS repositories configured.'
for package in archlinux-keyring cachyos-keyring; do
    pacman -Q "$package" >/dev/null 2>&1 || dependencies+=("$package")
done
for tool in sha256sum sha512sum realpath mktemp tee cp rm mkdir cat base64; do
    if ! command -v "$tool" >/dev/null; then
        dependencies+=(coreutils)
        break
    fi
done
if (( ${#dependencies[@]} )); then
    command -v pacman >/dev/null || fail 'Automatic dependency installation requires CachyOS/Arch and pacman.'
    printf 'Installing missing host dependencies: %s\n' "${dependencies[*]}"
    "${rootcmd[@]}" pacman -S --needed --noconfirm "${dependencies[@]}" || fail 'Dependency installation failed; fix the pacman error above and rerun the script.'
    hash -r
fi
for tool in xorriso unsquashfs mksquashfs python3 sha256sum sha512sum realpath mktemp tee cmp cp rm mkdir cat arch-chroot unshare tar gzip base64; do
    command -v "$tool" >/dev/null || fail "Missing command: $tool"
done
input=$(realpath -e -- "$1")
[[ -f $input ]] || fail 'Input must be an ISO file, not a disk/device.'
output=$(realpath -m -- "${2:-${input%.*}-bcachefs-fixed.iso}")
[[ $input != "$output" ]] || fail 'Input and output must be different files.'
[[ ! -e $output && ! -L $output ]] || fail "Destination already exists: $output"
[[ ! -e $output.sha256 && ! -L $output.sha256 && ! -e $output.patch.log && ! -L $output.patch.log ]] || fail 'Output checksum or log already exists; choose another output name.'
[[ -d ${output%/*} && -w ${output%/*} ]] || fail 'Output directory must exist and be writable.'
# Put large temporary files on the output filesystem, not a potentially RAM-backed /tmp.
work=$(mktemp -d -- "${output%/*}/bcachefs-iso-patch.XXXXXXXX")
exec 3>&1 4>&2
exec > >(tee "$work/patch.log") 2>&1
log_pid=$!
trap 'printf "\nPatch stopped at line %s. Original ISO retained. Work/log: %s\n" "$LINENO" "$work" >&2' ERR
printf 'Input:  %s\nOutput: %s\nWork:   %s\n' "$input" "$output" "$work"
printf 'Allow roughly 50-70 GiB free. This builds Calamares and bcachefs and updates the image.\n'

mkdir "$work/payload"
